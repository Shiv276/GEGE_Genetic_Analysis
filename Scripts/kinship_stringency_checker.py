import pandas as pd

from config import KINSHIP_DIR, PROCESSED_DATA


"""
This works with the processed .kin0 files generated by plink_pipeline.py.

This tests the KINSHIP values generated by KING from a range of r^2 thresholds in LD pruning.
This should reveal which individuals are related after LD pruning, and provide a better idea of r^2 threshold stringency.

Broadly trying to:
    1. Determine how strongly LD-pruned kinship estimates agree with the all-SNP estimates.
    2. Test whether each marker set preserves the known family/KINSHIP signals.
    3. Use these results to select a strong LD-pruning threshold that ideally preserves the most number of SNPs.
"""

KINSHIP_FILES = {
    'all': KINSHIP_DIR / "kinship_all.kin0",
    "r2_0.1": KINSHIP_DIR /"kinship_pruned_5000kb_r2_0.1.kin0",
    "r2_0.2": KINSHIP_DIR /"kinship_pruned_5000kb_r2_0.2.kin0",
    "r2_0.5": KINSHIP_DIR /"kinship_pruned_5000kb_r2_0.5.kin0",
    "r2_0.8": KINSHIP_DIR /"kinship_pruned_5000kb_r2_0.8.kin0"
    }

FROG_FILE = (PROCESSED_DATA /"individual_froh_metadata.csv")



def load_king_file(path):
    """
    Loads a specific .kin0 file for processing.
    """
    df = pd.read_csv(path, sep=r"\s+")

    # Normalise PLINK column names
    rename_map = {
        "IID1": "ID1",
        "IID2": "ID2",
        }

    df = df.rename(columns=rename_map)

    return df


def load_all_kinship():

    datasets = {}

    for name, kin0_file in KINSHIP_FILES.items():

        df = load_king_file(kin0_file)

        #Ideally, for 910 pairwise individals, we would see (((910 * (910 - 1 )) / 2) = 413,595 unique pairs.
        print(f"{name}: {df.shape[0]:,} pairs")

        #Storing each df in a dict (previous dict held labels : filenames / paths)
        datasets[name] = df

    return datasets


def load_frog_metadata():
    """
    Loads frog metadata containing IIDs and clutch (family / subpop)

    Helps determine the effect of different r^2 LD thresholds based
    on how KINSHIP changes between family.
    """
    return pd.read_csv(FROG_FILE)


def make_comparison_table(datasets):

    #Way to find the first dataset and merge the rest.
    #Admittedly not the greatest approach (pd.concat is far more efficient), but is more familiar to me.
    isFirst = False

    for name, df in datasets.items():

        temp = df[["ID1", "ID2", "KINSHIP"]].copy()
        temp = temp.rename(columns={"KINSHIP": f"{name}_KINSHIP"})
        

        if not isFirst:
            comparison = temp
            isFirst = True

        else:
            comparison = comparison.merge(
                temp,
                on=["ID1", "ID2"],
                how="inner",
                validate="one_to_one"
            )

    return comparison


def compare_kinship_sets(comparison):

    #We are comparing LD-pruned kinships to the reference, which are kinship calculations on ALL individals
    reference = "all_KINSHIP"

    results = []

    for label in ["r2_0.1_KINSHIP","r2_0.2_KINSHIP","r2_0.5_KINSHIP","r2_0.8_KINSHIP"]:

        #Correlation retrns a 2x2 symmetrical matrix so extracting [0, 1] or [1, 0] works.
        pearson = comparison[[reference, label]].corr(method="pearson").iloc[0, 1]
        spearman = comparison[[reference, label]].corr(method="spearman").iloc[0, 1]

        #Pearson returns the linearity, and Spearman returns how the rank-distribtion changed relative to 'ALL' (reference)
        #The rank distribution is arguably more importrant because we care more about the pairwise relationships between indivs. 

        difference = (comparison[label] -comparison[reference])

        mae = difference.abs().mean()
        median_abs_diff = (difference.abs().median())

        results.append({
            "marker_set": label,
            "pearson_vs_all": pearson,
            "spearman_vs_all": spearman,
            "mean_absolute_difference": mae,
            "median_absolute_difference":median_abs_diff
        })

    return pd.DataFrame(results)


def attach_family_metadata(kinship_df, frogs):

    #We only need individual ID and clutch / subpop to merge families.
    metadata = frogs[['IID', 'clutch']].copy()

    #Segmenting dataset into frog1 and frog2 because we're comparing pairwise KINSHIP
    frog1 = metadata.rename(columns={'IID': 'ID1', 'clutch': 'clutch1'})
    frog2 = metadata.rename(columns={'IID': 'ID2', 'clutch': 'clutch2'})


    # Attach pedigree information for frog 1.
    pairs = kinship_df.merge( frog1, on="ID1", how="left", validate="many_to_one")

    # Attach pedigree information for frog 2.
    pairs = pairs.merge( frog2, on="ID2", how="left", validate="many_to_one")


    pairs["same_family"] = pairs["clutch1"] == pairs["clutch2"]
    
    return pairs


#Check whether each marker set recovers family structure
def summarise_family_signal(datasets,frogs):
    results = []

    for label, df in datasets.items():


        pairs = attach_family_metadata(df, frogs)

        #Genomic kinship between members of the same pedigree family.
        within = pairs.loc[pairs["same_family"], "KINSHIP"]

        #Genomic kinship between frogs from different pedigree families.
        between = pairs.loc[~pairs["same_family"], "KINSHIP"]


        results.append({
            "marker_set": label,
            "within_n": len(within),
            "between_n": len(between),
            "within_mean": within.mean(),
            "between_mean": between.mean(),
            "within_median": within.median(),
            "between_median": between.median(),
            "mean_difference": within.mean() - between.mean(),
            "median_difference": within.median() - between.median()  
            })


    return pd.DataFrame(results)



def save_comparison(comparison, robustness_summary, family_summary):
    comparison.to_csv(KINSHIP_DIR / "kinship_pruning_comparison.csv", index=False)
    robustness_summary.to_csv(KINSHIP_DIR / "kinship_pruning_summary.csv", index=False)
    family_summary.to_csv(KINSHIP_DIR / "kinship_family_validation.csv", index=False)



def main():
    #Load KING estimates
    datasets = load_all_kinship()

    #Load known clutch / subpop information
    frogs = load_frog_metadata()


    #Compare LD pruned estimates with all-SNP KING data
    comparison = make_comparison_table(datasets)
    robustness_summary = compare_kinship_sets(comparison)

    print("\nKinship robustness:")
    print(robustness_summary)


    #Compare LD pruned estimates with recovery of known clutch / subpop structure

    family_summary = summarise_family_signal(datasets, frogs)

    print("\nPedigree-family validation:")
    print(family_summary)



    #Save outputs
    save_comparison(comparison,robustness_summary,family_summary)



if __name__ == "__main__":
    main()


"""
An r^2 = 0.5 LD-pruning threshold was selected for primary pairwise kinship analyses because it substantially
reduced marker redundancy, retaining 9,099 SNPs from the ~39,700 post-QC markers, while preserving family structure.

The clutch / family signal was retained when comparing KINSHIP within known family structures.

Below is a summary of the output from plink_pipeline.py:
---
r2=0.1: 3664 retained; 36017 removed
r2=0.2: 5662 retained; 34019 removed
r2=0.5: 9099 retained; 30582 removed
r2=0.8: 13125 retained; 26556 removed
---

A more stringent figure of 0.2 retained 5,662 which means using r^2 = 0.5 almost doubled the number of markers.

Based on these tests, a figure of 0.5 preserves strong consistency with all-marker KING estimates; Pearson r = 0.979,
Spearman r = 0.950. The Spearman correlation being >= 0.95 under r^2 = 0.5 was a large contributer to this choice.

More importantly however, using a value of 0.2 loses 86% of the total SNP count, without substantially changing 
family structure.

"""